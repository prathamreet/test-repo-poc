import os
import re
import json
import urllib.request
import urllib.error
import boto3

# Initialize the AWS DevOps Agent client
devops_client = boto3.client('devops-agent')

GITHUB_TOKEN = os.environ.get('GITHUB_TOKEN')          # GitHub PAT or GitHub App Token
GITHUB_REPO_OWNER = os.environ.get('GITHUB_REPO_OWNER')  # e.g., "my-org"
GITHUB_REPO_NAME = os.environ.get('GITHUB_REPO_NAME')    # e.g., "my-repo"

def lambda_handler(event, context):
    """
    Triggered by EventBridge rule matching 'aws.aidevops'.
    Retrieves the final synthesis from the agent journal and comments on the GitHub PR.
    """
    print("Received EventBridge event:", json.dumps(event))

    detail = event.get('detail', {})
    agent_space_id = detail.get('agentSpaceId')
    execution_id = detail.get('executionId')
    incident_id = detail.get('incidentId', '')

    if not agent_space_id or not execution_id:
        print("Missing agentSpaceId or executionId.")
        return {'statusCode': 400, 'body': 'Missing required identifiers'}

    # 1. Extract PR number from incidentId format: "gh-pr-42-12345"
    pr_match = re.search(r'gh-pr-(\d+)', incident_id)
    if not pr_match:
        print(f"Not a PR incident (incidentId='{incident_id}'). Skipping comment.")
        return {'statusCode': 200, 'body': 'Ignored non-PR incident'}

    pr_number = pr_match.group(1)

    # 2. Fetch journal records from the Agent Space
    try:
        response = devops_client.list_journal_records(
            agentSpaceId=agent_space_id,
            executionId=execution_id
        )
    except Exception as e:
        print(f"Error calling list_journal_records: {e}")
        return {'statusCode': 500, 'body': str(e)}

    # 3. Extract the final findings / synthesis
    records = response.get('journalRecords', [])
    findings = extract_synthesis(records)

    # 4. Format the Markdown comment
    comment_body = f"""### 🤖 AWS DevOps Agent — PR Failure Triage

{findings}

---
*Generated by AWS DevOps Agent Space (`{agent_space_id}`) for PR #{pr_number}.*
"""

    # 5. Post to the GitHub PR (in GitHub REST API, PR comments use the issues comments endpoint)
    post_comment(pr_number, comment_body)
    return {'statusCode': 200, 'body': 'Comment posted successfully'}


def extract_synthesis(records):
    if not records:
        return "_No specific failure diagnosis was recorded in the journal._"

    for record in reversed(records):
        rec_type = record.get('recordType', '').upper()
        if rec_type in ['SYNTHESIS', 'FINDING', 'SUMMARY', 'REPORT']:
            return record.get('content', '')

    return records[-1].get('content', str(records[-1]))


def post_comment(pr_number, comment_markdown):
    url = f"https://api.github.com/repos/{GITHUB_REPO_OWNER}/{GITHUB_REPO_NAME}/issues/{pr_number}/comments"
    headers = {
        "Authorization": f"Bearer {GITHUB_TOKEN}",
        "Accept": "application/vnd.github+json",
        "User-Agent": "AWS-DevOps-Agent-PR-Commenter"
    }
    payload = json.dumps({"body": comment_markdown}).encode('utf-8')

    req = urllib.request.Request(url, data=payload, headers=headers, method='POST')
    try:
        with urllib.request.urlopen(req) as resp:
            print(f"Comment posted on PR #{pr_number}. HTTP {resp.status}")
    except urllib.error.HTTPError as err:
        print(f"GitHub API Error: {err.code} - {err.read().decode('utf-8')}")
        raise

